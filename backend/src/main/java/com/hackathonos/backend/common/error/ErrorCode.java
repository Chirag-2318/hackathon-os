package com.hackathonos.backend.common.error;

/**
 * Standardized application error codes for API error responses.
 */
public enum ErrorCode {
    BAD_REQUEST("BAD_REQUEST"),
    UNAUTHORIZED("UNAUTHORIZED"),
    FORBIDDEN("FORBIDDEN"),
    NOT_FOUND("NOT_FOUND"),
    CONFLICT("CONFLICT"),
    TOO_MANY_REQUESTS("TOO_MANY_REQUESTS"),
    INTERNAL_SERVER_ERROR("INTERNAL_SERVER_ERROR"),
    UNPROCESSABLE_ENTITY("UNPROCESSABLE_ENTITY"),

    // Room & permissions
    ROOM_NOT_FOUND("ROOM_NOT_FOUND"),
    MEMBER_NOT_FOUND("MEMBER_NOT_FOUND"),
    NOT_A_MEMBER("NOT_A_MEMBER"),
    LEADER_REQUIRED("LEADER_REQUIRED"),
    ROOM_FULL("ROOM_FULL"),
    INVALID_CODE("INVALID_CODE"),
    CANNOT_REMOVE_SELF("CANNOT_REMOVE_SELF"),
    TRANSFER_LEADERSHIP_FIRST("TRANSFER_LEADERSHIP_FIRST"),
    INVALID_STAGE_TRANSITION("INVALID_STAGE_TRANSITION"),
    STAGE_LOCKED("STAGE_LOCKED"),
    TASK_BLOCKED("TASK_BLOCKED"),

    // Validation & files
    VALIDATION_FAILED("VALIDATION_FAILED"),
    INVALID_DATES("INVALID_DATES"),
    FILE_TOO_LARGE("PAYLOAD_TOO_LARGE"),
    INVALID_FILE_TYPE("INVALID_FILE_TYPE"),
    SSRF_BLOCKED("SSRF_BLOCKED"),

    // AI
    AI_NOT_CONFIGURED("AI_NOT_CONFIGURED"),
    AI_FAILED("AI_FAILED"),
    AI_RESTRICTED_BY_EVENT("AI_RESTRICTED_BY_EVENT"),
    AI_OUTPUT_ERROR("AI_OUTPUT_ERROR"),
    AI_OUTPUT_INVALID("AI_OUTPUT_INVALID"),
    AI_UNAVAILABLE("AI_UNAVAILABLE"),
    AI_CIRCUIT_OPEN("AI_CIRCUIT_OPEN"),

    // Upstream & Concurrency
    GITHUB_UNAVAILABLE("GITHUB_UNAVAILABLE"),
    VERSION_CONFLICT("VERSION_CONFLICT"),
    IDEMPOTENCY_CONFLICT("IDEMPOTENCY_CONFLICT");


    private final String code;

    ErrorCode(String code) {
        this.code = code;
    }

    public String getCode() {
        return code;
    }

    @Override
    public String toString() {
        return code;
    }
}
